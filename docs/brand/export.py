def text_width(text, scale):
    return (len(text) * 6 - 1) * scale


def letter(c, text, x, y, scale, colour):
    for i, ch in enumerate(text.upper()):
        for row, bits in enumerate(FONT[ch]):
            for col, bit in enumerate(bits):
                if bit == "1":
                    c.rect(x + (i * 6 + col) * scale, y + row * scale, scale, scale, colour)


def poster(w, h, out):
    """The name, the line and the scene: link previews, the README banner.
    The lettering fills the left part, the warden and portal the right."""
    c = Canvas(w, h, BOX)
    floor = h - h // 5
    c.rect(0, floor, w, h - floor, FLOOR)
    margin = w // 12
    a = max(2, int(h * 0.55) // 25)          # scene scale: the portal is 55% of the height
    portal_x = w - margin - 32 * a
    c.rect(margin, floor - a, portal_x + 16 * a - margin, a, RAIL)
    c.art(art("portal"), portal_x, floor - 25 * a, a, lamp="#3cc27a", halo="#1f5b3f")
    c.art(art("wardenLantern"), portal_x - 16 * a, floor - 15 * a, a, lamp="#3cc27a")
    big = max(2, int(w * 0.42) // text_width("TUNWARDEN", 1))
    small = max(1, int(w * 0.42) // text_width("KEEPS YOUR TUNNELS RUNNING.", 1))
    top = h // 6
    letter(c, "TUNWARDEN", margin, top, big, "#efe9d8")
    letter(c, "KEEPS YOUR TUNNELS RUNNING.", margin, top + 7 * big + 3 * small, small, "#c4bfae")
    c.png(out)


def write_bytes(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)


def write_text(path, text):
    write_bytes(path, text.encode())
    print("wrote", os.path.relpath(path, ROOT))


def main():
    ts = typescript()
    write_text(os.path.join(ROOT, "apps/web/src/art/pixels.ts"), ts)
    write_text(os.path.join(ROOT, "apps/desktop/src/art/pixels.ts"), ts)
    installer(os.path.join(ROOT, "apps/desktop/src-tauri/installer"))
    print("wrote apps/desktop/src-tauri/installer/")
    # Link previews (Open Graph 1200x630), GitHub's social preview (1280x640,
    # uploaded by hand under Settings), and the README banner.
    poster(1200, 630, os.path.join(ROOT, "apps/web/src/app/opengraph-image.png"))
    poster(1280, 640, os.path.join(HERE, "social-preview.png"))
    poster(1280, 320, os.path.join(HERE, "banner.png"))
    print("wrote opengraph-image.png, social-preview.png, banner.png")


if __name__ == "__main__":
    main()
