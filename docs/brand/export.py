#!/usr/bin/env python3
"""Exports the brand pixel art to every place that shows it.

    python3 docs/brand/export.py

Reads the drawings in concepts/make.py and writes:

- apps/web/src/art/pixels.ts and apps/desktop/src/art/pixels.ts: one SVG path
  per colour for each drawing, pixel runs merged;
- apps/desktop/src-tauri/installer/: the macOS disk image background and the
  Windows installer images;
- apps/web/src/app/opengraph-image.png, docs/brand/social-preview.png and
  docs/brand/banner.png: the link preview, GitHub's social preview and the
  README banner.

A lantern's glass is the colour `lamp`: the page or app fills it in
with the state it shows. CI runs this and fails if any output changes.
"""

import os
import struct
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(HERE, "concepts"))

import make  # noqa: E402

LAMP = "lamp"


class Art:
    def __init__(self, name, grid, x=0, y=0, w=None, h=None):
        self.name = name
        self.px = grid.px
        self.x, self.y = x, y
        self.w = w or getattr(grid, "w", grid.n)
        self.h = h or getattr(grid, "h", grid.n)


def portal():
    g = make.Grid(32)
    make.tunnel(g, 16, 4, 13, 9, 28, ("#56627a", "#434e63", "#323b4c"), ("#05070a", "#0b0f15"))
    return g


def lamp_disc(g, cx, cy, halo=True):
    """The tray and icon lamp: a disc of `lamp` with a halo ring."""
    for dy in range(-3, 4):
        for dx in range(-3, 4):
            d = (dx * dx + dy * dy) ** 0.5
            if d <= 1.6:
                g.set(cx + dx, cy + dy, LAMP)
            elif d <= 3.1 and halo:
                g.set(cx + dx, cy + dy, "halo")
    g.set(cx - 1, cy - 1, "#ffffff")


def lit_portal():
    g = portal()
    lamp_disc(g, 16, 18)
    return g


ARTS = [
    Art("portal", lit_portal(), y=4, w=32, h=25),
    Art("icon", make.concept_b("brand")),
    Art("trayArch", make.tray_portal("#e9e6dc", None)),
    Art("smallPortal", make.small_portal(LAMP)),
    Art("wardenStand", make.warden("stand")),
    Art("wardenWave", make.warden("wave")),
    Art("wardenLantern", make.warden("lantern", LAMP)),
    Art("wardenRest", make.warden("rest")),
]


# --- TypeScript ------------------------------------------------------------------

def paths(art):
    by_colour = {}
    for y in range(art.y, art.y + art.h):
        x = art.x
        while x < art.x + art.w:
            c = art.px.get((x, y))
            if not c:
                x += 1
                continue
            start = x
            while x < art.x + art.w and art.px.get((x, y)) == c:
                x += 1
            by_colour.setdefault(c, []).append(f"M{start} {y}h{x - start}v1h-{x - start}z")
    return sorted(by_colour.items())


def typescript():
    out = [
        "// Generated by docs/brand/export.py from docs/brand/concepts/make.py. Do not edit.\n",
        "// A path coloured \"lamp\" or \"halo\" takes the colour the page gives it.\n",
        "export type PixelArt = { x: number; y: number; width: number; height: number; paths: [string, string][] };\n",
    ]
    for a in ARTS:
        rows = ",\n".join(f'    ["{c}", "{"".join(d)}"]' for c, d in paths(a))
        out.append(
            f"\nexport const {a.name}: PixelArt = {{\n  x: {a.x},\n  y: {a.y},\n  width: {a.w},\n"
            f"  height: {a.h},\n  paths: [\n{rows},\n  ],\n}};\n"
        )
    return "".join(out)


# --- Installer images ---------------------------------------------------------------

def hexrgb(c):
    return tuple(int(c[i:i + 2], 16) for i in (1, 3, 5))


class Canvas:
    def __init__(self, w, h, bg):
        self.w, self.h = w, h
        self.px = [[hexrgb(bg)] * w for _ in range(h)]

    def rect(self, x, y, w, h, c):
        for yy in range(max(0, y), min(self.h, y + h)):
            for xx in range(max(0, x), min(self.w, x + w)):
                self.px[yy][xx] = hexrgb(c)

    def art(self, a, x0, y0, scale, lamp="#ffe8a3", halo="#6b5f3a"):
        for (x, y), c in a.px.items():
            if not (a.x <= x < a.x + a.w and a.y <= y < a.y + a.h):
                continue
            c = {LAMP: lamp, "halo": halo}.get(c, c)
            self.rect(x0 + (x - a.x) * scale, y0 + (y - a.y) * scale, scale, scale, c)

    def bmp(self, path):
        """24-bit BMP, which the Windows installers require."""
        row = (self.w * 3 + 3) & ~3
        data = bytearray()
        for y in reversed(range(self.h)):
            line = bytearray()
            for r, g, b in self.px[y]:
                line += bytes((b, g, r))
            data += line + b"\0" * (row - len(line))
        header = struct.pack("<2sIHHI", b"BM", 54 + len(data), 0, 0, 54)
        info = struct.pack("<IiiHHIIiiII", 40, self.w, self.h, 1, 24, 0, len(data), 2835, 2835, 0, 0)
        write_bytes(path, header + info + bytes(data))

    def png(self, path):
        import zlib
        raw = b"".join(b"\0" + bytes(v for p in row for v in p) for row in self.px)

        def chunk(kind, body):
            return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body) & 0xFFFFFFFF)

        data = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", self.w, self.h, 8, 2, 0, 0, 0))
        data += chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
        write_bytes(path, data)


BOX = "#1c2420"
FLOOR = "#141a17"
PANEL = "#2e3a35"
RAIL = "#e9e6dc"


def art(name):
    return next(a for a in ARTS if a.name == name)


def installer(out):
    # macOS disk image window, 660x400 points (Tauri's default window size).
    # The app icon sits at (180, 170) and Applications at (480, 170): a track
    # runs between them, with the warden beside the portal.
    # Finder writes the icon labels in black, so they sit on the rule book's paper.
    c = Canvas(660, 400, "#ece5d3")
    c.rect(0, 300, 660, 100, FLOOR)
    for x in range(262, 400, 24):
        c.rect(x, 162, 8, 16, "#8a7f66")
    c.rect(250, 166, 160, 8, "#1d2420")
    # arrow head
    for i in range(12):
        c.rect(398 + i, 158 + i, 4, 24 - 2 * i, "#1d2420")
    c.art(art("wardenLantern"), 286, 316, 4, lamp="#3cc27a", halo="#1f5b3f")
    c.art(art("smallPortal"), 380, 324, 4, lamp="#3cc27a")
    c.png(os.path.join(out, "dmg-background.png"))
    # NSIS (.exe) sidebar 164x314 and header 150x57.
    s = Canvas(164, 314, BOX)
    s.rect(0, 250, 164, 64, FLOOR)
    s.art(art("portal"), 18, 60, 4, lamp="#ffe8a3")
    s.art(art("wardenWave"), 46, 196, 3)
    s.bmp(os.path.join(out, "nsis-sidebar.bmp"))
    h = Canvas(150, 57, "#ffffff")
    h.art(art("smallPortal"), 102, 4, 3, lamp="#ffe8a3")
    h.bmp(os.path.join(out, "nsis-header.bmp"))

    # WiX (.msi) banner 493x58 (text sits on the left) and dialog 493x312
    # (the left 164 px show behind the welcome text's margin; the rest is white).
    b = Canvas(493, 58, "#ffffff")
    b.art(art("smallPortal"), 441, 5, 3, lamp="#ffe8a3")
    b.bmp(os.path.join(out, "wix-banner.bmp"))
    d = Canvas(493, 312, "#ffffff")
    d.rect(0, 0, 164, 312, BOX)
    d.rect(0, 250, 164, 62, FLOOR)
    d.art(art("portal"), 18, 60, 4, lamp="#ffe8a3")
    d.art(art("wardenWave"), 46, 196, 3)
    d.bmp(os.path.join(out, "wix-dialog.bmp"))


