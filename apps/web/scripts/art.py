#!/usr/bin/env python3
"""Turns the brand pixel art into path data for the website.

    python3 apps/web/scripts/art.py

Reads the drawings in docs/brand/concepts/make.py (concept B's portal, the
friendly warden) and writes src/art/pixels.ts: one SVG path per colour, each
pixel run merged into a single rectangle, so the site draws the same grids
the icon uses. The portal is drawn without its lamp and its perspective track:
the lamp is drawn by the page in the tunnel's state colour, and the diagram's
own rails run into the mouth.
"""

import os
import sys

sys.dont_write_bytecode = True

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "docs", "brand", "concepts"))

import make  # noqa: E402


def paths(grid):
    """Grid -> [(colour, d)], one path per colour, runs merged per row."""
    by_colour = {}
    for y in range(grid.n):
        x = 0
        while x < grid.n:
            c = grid.px.get((x, y))
            if not c:
                x += 1
                continue
            start = x
            while x < grid.n and grid.px.get((x, y)) == c:
                x += 1
            by_colour.setdefault(c, []).append(f"M{start} {y}h{x - start}v1h-{x - start}z")
    return [(c, "".join(d)) for c, d in sorted(by_colour.items())]


def portal():
    g = make.Grid(32)
    make.tunnel(g, 16, 4, 13, 9, 28, ("#56627a", "#434e63", "#323b4c"), ("#05070a", "#0b0f15"))
    return g


def warden():
    g = make.Grid(15)
    pal = dict(K="#0b0f15", h="#ff8f9c", H="#ef5b6d", V="#0b0f15", E="#f4f7ff",
               B="#3d7bea", b="#2a5bb8", Y="#ffe08a", D="#18202c")
    g.sprite(1, 0, make.FRIENDLY, pal)
    return g


def icon():
    return make.concept_b("brand")


def emit(name, grid, w, h, x=0, y=0):
    rows = ",\n".join(f'    ["{c}", "{d}"]' for c, d in paths(grid))
    return f"export const {name}: PixelArt = {{\n  x: {x},\n  y: {y},\n  width: {w},\n  height: {h},\n  paths: [\n{rows},\n  ],\n}};\n"


def main():
    out = [
        "// Generated by scripts/art.py from docs/brand/concepts/make.py. Do not edit.\n",
        "export type PixelArt = { x: number; y: number; width: number; height: number; paths: [string, string][] };\n\n",
        emit("portal", portal(), 32, 25, y=4),
        "\n",
        emit("warden", warden(), 14, 15),
        "\n",
        emit("icon", icon(), 32, 32),
        "\n",
        # The tray glyph's arch; the page draws its lamp in the state colour.
        emit("trayArch", make.tray_portal("#e9e6dc", None), 16, 16),
    ]
    path = os.path.join(HERE, "..", "src", "art", "pixels.ts")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("".join(out))
    print("wrote", os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
